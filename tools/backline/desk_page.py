def render():
    with open(SOURCE, encoding="utf-8", newline="") as f:
        text = f.read()
    body = "".join("    %r\n" % line for line in text.splitlines(True))
    return HEADER + body + ")\n"


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(TARGET, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            sys.exit("apps/backline/page_data.py is out of date: run python tools/backline/desk_page.py and commit it")
        return
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote apps/backline/page_data.py")


if __name__ == "__main__":
    main(sys.argv[1:])
