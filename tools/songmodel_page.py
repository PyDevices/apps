"""Write ``lib/songmodel/page_data.py``, the front panel page as Python.

    python tools/songmodel_page.py           # write it from page.html
    python tools/songmodel_page.py --check   # fail if it is out of date

A ``mip`` or ``omip`` install, and a frozen build, carry a package's ``.py``
files and nothing else, so the page travels as a string in a module and
``songmodel.page()`` serves it from there. Edit ``page.html``, then run this.
"""

import os
import sys

LIB = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lib", "songmodel")
SOURCE = os.path.join(LIB, "page.html")
TARGET = os.path.join(LIB, "page_data.py")

HEADER = '''# SPDX-FileCopyrightText: 2026 Brad Barnett
#
# SPDX-License-Identifier: MIT

"""The front panel page, as ``songmodel.page()`` serves it.

Generated by tools/songmodel_page.py from page.html: edit that, not this.
"""

HTML = (
'''


def render():
    with open(SOURCE, encoding="utf-8", newline="") as f:
        text = f.read()
    lines = text.splitlines(True)
    body = "".join("    %r\n" % line for line in lines)
    return HEADER + body + ")\n"


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(TARGET, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            sys.exit("lib/songmodel/page_data.py is out of date: run python tools/songmodel_page.py and commit it")
        return
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote lib/songmodel/page_data.py")


if __name__ == "__main__":
    main(sys.argv[1:])
