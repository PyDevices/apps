"""Write app/boot_config.js: what each worker loads.

    .venv/bin/python tools/gen_boot.py

Run after scripts/fetch_wheels.py or scripts/fetch_midi.py, or after adding
an app module. The page (index.html) reads it.
"""

import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


# The desktop app's MIDI port and its link between processes (hmilink, and
# the song as its model): scripts/fetch_midi.py fetches them beside the rest.
DESKTOP_ONLY = ("vendor/lib/midiports/windows.py", "vendor/lib/hmilink/", "lib/songmodel/link.py")
# songmodel (the song model Ostinato shares with Vamp) is in the apps repo's lib/, two
# folders up; iconkit (its icons) is in the pydevices repo, where tools/iconkit_lib.py
# finds it. The page fetches both as lib/<package>/...: tools/serve.py serves them
# there, and a published copy carries them at that path.
LIB = ROOT.parent.parent / "lib"
sys.path.insert(0, str(ROOT / "tools"))
import iconkit_lib  # noqa: E402


def tree(folder, dest="", root=ROOT, url=""):
    out = {}
    base = root / folder
    for d, _, fs in os.walk(base):
        for f in sorted(fs):
            if f.endswith(".py"):
                p = pathlib.Path(d) / f
                rel = p.relative_to(base).as_posix()
                src = url + p.relative_to(root).as_posix()
                if not src.startswith(DESKTOP_ONLY):
                    out[src] = dest + rel
    return out


def main():
    w = json.loads((ROOT / "wheels.json").read_text())
    whl = lambda n: "vendor/wheels/" + w[n]["file"]
    shared = tree("songmodel", "songmodel/", LIB, "lib/")
    # iconkit's icons, drawn by LVGL; its pygraphics drawing (gfx.py) and MicroPython manifest aren't used here.
    icons = {src: dest for src, dest in tree("iconkit", "iconkit/", iconkit_lib.find(), "lib/").items()
             if not src.endswith(("/gfx.py", "/manifest.py"))}
    ui = {"packages": [whl("pydevices"), whl("pydevices-lvgl")],
          "files": {**shared, **icons, **tree("app/ui"), **tree("vendor/board")}}
    engine = {"packages": [whl("pydevices"), whl("numpy"), whl("omnipython-audiodsp"), whl("omnipython-audioeffects"),
                           whl("omnipython-audioinstruments")],
              "files": {**shared, **tree("app/engine"), **tree("vendor/lib")}}
    cfg = {"ui": ui, "engine": engine, "versions": {k: v["version"] for k, v in w.items()}}
    (ROOT / "app" / "boot_config.js").write_text(
        "// Generated by tools/gen_boot.py: what each worker loads.\nexport default "
        + json.dumps(cfg, indent=1) + ";\n")
    # Everything an offline start needs, for the service worker to fetch at
    # install: workers fetch most of it before the worker controls the page.
    pyodide = ["vendor/pyscript/pyodide/" + f for f in ("pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm",
                                                       "python_stdlib.zip", "pyodide-lock.json")]
    fonts = ["https://raw.githubusercontent.com/PyDevices/lvgl-bindings/v9.5.22/fonts/montserrat_%d.bin" % n
             for n in (12, 14, 16, 20, 24, 28, 36, 48)]
    assets = sorted("assets/" + f.name for f in (ROOT / "assets").iterdir() if f.suffix in (".bin", ".json"))
    files = sorted(set(ui["packages"] + engine["packages"] + list(ui["files"]) + list(engine["files"])))
    shell = ["./", "index.html", "manifest.json", "icon-192.png", "icon-512.png", "app/boot_config.js",
             "workers/host.js", "workers/python_worker.js", "workers/audio_worklet.js"]
    (ROOT / "app" / "precache.json").write_text(json.dumps(shell + pyodide + assets + files + fonts, indent=1) + "\n")
    print("ui files", len(ui["files"]), "engine files", len(engine["files"]),
          "precache", len(shell + pyodide + assets + files + fonts))


if __name__ == "__main__":
    main()
